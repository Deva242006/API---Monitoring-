export type UserRole = 'ADMIN' | 'DEVELOPER' | 'VIEWER';

export interface User {
  id: number;
  email: string;
  fullName: string;
  role: UserRole;
  active: boolean;
  avatarUrl?: string;
  phone?: string;
  createdAt?: string;
  lastLoginAt?: string;
}

export type ApiStatus = 'HEALTHY' | 'DEGRADED' | 'DOWN' | 'UNKNOWN';
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE';

export interface MonitoredApi {
  id: number;
  name: string;
  endpointUrl: string;
  httpMethod: HttpMethod;
  expectedStatusCode: number;
  timeoutMs: number;
  monitoringIntervalSeconds: number;
  projectId: number;
  projectName: string;
  active: boolean;
  description?: string;
  currentStatus: ApiStatus;
  consecutiveFailures: number;
  lastCheckedAt?: string;
  lastResponseTimeMs?: number;
  createdAt: string;
}

export interface Project {
  id: number;
  name: string;
  description?: string;
  owner: User;
  active: boolean;
  members: User[];
  apiCount: number;
  createdAt: string;
  updatedAt: string;
}

export interface HealthCheck {
  id: number;
  apiId: number;
  apiName: string;
  status: ApiStatus;
  responseTimeMs?: number;
  statusCode?: number;
  errorMessage?: string;
  checkedAt: string;
}

export type IncidentSeverity = 'LOW' | 'MEDIUM' | 'HIGH' | 'CRITICAL';
export type IncidentStatus = 'OPEN' | 'ACKNOWLEDGED' | 'IN_PROGRESS' | 'RESOLVED';

export interface Incident {
  id: number;
  title: string;
  description?: string;
  apiId: number;
  apiName: string;
  severity: IncidentSeverity;
  status: IncidentStatus;
  assignedToId?: number;
  assignedToName?: string;
  createdById?: number;
  createdByName?: string;
  autoGenerated: boolean;
  resolvedAt?: string;
  resolvedByName?: string;
  createdAt: string;
  updatedAt: string;
}

export interface IncidentComment {
  id: number;
  incidentId: number;
  userId: number;
  userName: string;
  content: string;
  createdAt: string;
}

export interface NotificationItem {
  id: number;
  title: string;
  message: string;
  type: string;
  isRead: boolean;
  referenceId?: number;
  referenceType?: string;
  createdAt: string;
}

export interface DashboardSummary {
  totalApis: number;
  healthyApis: number;
  degradedApis: number;
  downApis: number;
  activeIncidents: number;
  resolvedIncidents: number;
  uptimePercentage: number;
  avgResponseTime: number;
  failedChecks: number;
  totalChecks: number;
}

export interface PagedResponse<T> {
  content: T[];
  page: number;
  size: number;
  totalElements: number;
  totalPages: number;
  last: boolean;
}

export interface ApiResponse<T> {
  success: boolean;
  message: string;
  data: T;
  timestamp: string;
}

