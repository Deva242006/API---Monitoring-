package com.sentinel.incident.service;

import com.sentinel.common.dto.PagedResponse;
import com.sentinel.common.enums.IncidentSeverity;
import com.sentinel.common.enums.IncidentStatus;
import com.sentinel.common.exception.ResourceNotFoundException;
import com.sentinel.incident.dto.*;
import com.sentinel.incident.entity.Incident;
import com.sentinel.incident.entity.IncidentComment;
import com.sentinel.incident.repository.IncidentCommentRepository;
import com.sentinel.incident.repository.IncidentRepository;
import com.sentinel.monitoring.entity.MonitoredApi;
import com.sentinel.monitoring.repository.MonitoredApiRepository;
import com.sentinel.notification.service.NotificationService;
import com.sentinel.user.entity.User;
import com.sentinel.user.repository.UserRepository;
import com.sentinel.audit.service.AuditService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Sort;
import org.springframework.messaging.simp.SimpMessagingTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;

@Service
public class IncidentService {

    private static final Logger log = LoggerFactory.getLogger(IncidentService.class);
    private final IncidentRepository incidentRepository;
    private final IncidentCommentRepository commentRepository;
    private final MonitoredApiRepository apiRepository;
    private final UserRepository userRepository;
    private final NotificationService notificationService;
    private final AuditService auditService;
    private final SimpMessagingTemplate messagingTemplate;

    public IncidentService(IncidentRepository incidentRepository,
                           IncidentCommentRepository commentRepository,
                           MonitoredApiRepository apiRepository,
                           UserRepository userRepository,
                           NotificationService notificationService,
                           AuditService auditService,
                           SimpMessagingTemplate messagingTemplate) {
        this.incidentRepository = incidentRepository;
        this.commentRepository = commentRepository;
        this.apiRepository = apiRepository;
        this.userRepository = userRepository;
        this.notificationService = notificationService;
        this.auditService = auditService;
        this.messagingTemplate = messagingTemplate;
    }

    /**
     * Automatically create an incident when consecutive failures exceed the threshold.
     * Prevents duplicates by checking for existing unresolved incidents.
     */
    @Transactional
    public void createAutoIncident(MonitoredApi api) {
        // Check for existing unresolved incident to prevent duplicates
        List<Incident> activeIncidents = incidentRepository.findActiveByApiId(api.getId());
        if (!activeIncidents.isEmpty()) {
            log.debug("Active incident already exists for API: {}", api.getName());
            return;
        }

        Incident incident = new Incident();
        incident.setTitle("API Down: " + api.getName());
        incident.setDescription("Automatic incident created after " + api.getConsecutiveFailures() +
                " consecutive failures for API endpoint: " + api.getEndpointUrl());
        incident.setApi(api);
        incident.setSeverity(IncidentSeverity.HIGH);
        incident.setStatus(IncidentStatus.OPEN);
        incident.setAutoGenerated(true);

        incident = incidentRepository.save(incident);
        log.info("Auto-incident created: {} for API: {}", incident.getId(), api.getName());

        // Notify project members
        notificationService.notifyIncidentCreated(incident);

        // WebSocket push
        try {
            messagingTemplate.convertAndSend("/topic/incidents",
                    Map.of("type", "INCIDENT_CREATED", "incidentId", incident.getId(),
                            "title", incident.getTitle(), "severity", incident.getSeverity().name()));
        } catch (Exception e) {
            log.debug("WebSocket notification failed: {}", e.getMessage());
        }
    }

    @Transactional
    public IncidentDto createManualIncident(CreateIncidentRequest request, User currentUser) {
        MonitoredApi api = apiRepository.findById(request.getApiId())
                .orElseThrow(() -> new ResourceNotFoundException("API", "id", request.getApiId()));

        Incident incident = new Incident();
        incident.setTitle(request.getTitle());
        incident.setDescription(request.getDescription());
        incident.setApi(api);
        incident.setSeverity(request.getSeverity());
        incident.setStatus(IncidentStatus.OPEN);
        incident.setCreatedBy(currentUser);
        incident.setAutoGenerated(false);

        if (request.getAssignedToId() != null) {
            User assignee = userRepository.findById(request.getAssignedToId())
                    .orElseThrow(() -> new ResourceNotFoundException("User", "id", request.getAssignedToId()));
            incident.setAssignedTo(assignee);
        }

        incident = incidentRepository.save(incident);
        auditService.log(currentUser, "CREATE", "INCIDENT", incident.getId(), "Incident created: " + incident.getTitle(), null);
        notificationService.notifyIncidentCreated(incident);

        return toDto(incident);
    }

    @Transactional(readOnly = true)
    public PagedResponse<IncidentDto> getIncidents(int page, int size, String status, String severity) {
        Page<Incident> incidents;
        PageRequest pageRequest = PageRequest.of(page, size, Sort.by("createdAt").descending());

        if (status != null && !status.isBlank()) {
            incidents = incidentRepository.findByStatus(IncidentStatus.valueOf(status.toUpperCase()), pageRequest);
        } else if (severity != null && !severity.isBlank()) {
            incidents = incidentRepository.findBySeverity(IncidentSeverity.valueOf(severity.toUpperCase()), pageRequest);
        } else {
            incidents = incidentRepository.findAllByOrderByCreatedAtDesc(pageRequest);
        }
        return toPagedResponse(incidents);
    }

    @Transactional(readOnly = true)
    public IncidentDto getIncidentById(Long id) {
        Incident incident = incidentRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Incident", "id", id));
        return toDto(incident);
    }

    @Transactional
    public IncidentDto assignIncident(Long incidentId, Long userId, User currentUser) {
        Incident incident = incidentRepository.findById(incidentId)
                .orElseThrow(() -> new ResourceNotFoundException("Incident", "id", incidentId));
        User assignee = userRepository.findById(userId)
                .orElseThrow(() -> new ResourceNotFoundException("User", "id", userId));

        incident.setAssignedTo(assignee);
        incident = incidentRepository.save(incident);

        auditService.log(currentUser, "ASSIGN", "INCIDENT", incidentId, "Assigned to: " + assignee.getFullName(), null);
        notificationService.notifyIncidentAssigned(incident, assignee);

        try {
            messagingTemplate.convertAndSend("/topic/incidents",
                    Map.of("type", "INCIDENT_ASSIGNED", "incidentId", incident.getId(),
                            "assignedTo", assignee.getFullName()));
        } catch (Exception e) {
            log.debug("WebSocket notification failed: {}", e.getMessage());
        }

        return toDto(incident);
    }

    @Transactional
    public IncidentDto updateIncidentStatus(Long incidentId, IncidentStatus newStatus, User currentUser) {
        Incident incident = incidentRepository.findById(incidentId)
                .orElseThrow(() -> new ResourceNotFoundException("Incident", "id", incidentId));

        incident.setStatus(newStatus);
        if (newStatus == IncidentStatus.RESOLVED) {
            incident.setResolvedAt(LocalDateTime.now());
            incident.setResolvedBy(currentUser);
            notificationService.notifyIncidentResolved(incident);
        }

        incident = incidentRepository.save(incident);
        auditService.log(currentUser, "STATUS_CHANGE", "INCIDENT", incidentId, "Status: " + newStatus.name(), null);

        try {
            messagingTemplate.convertAndSend("/topic/incidents",
                    Map.of("type", "INCIDENT_STATUS_CHANGED", "incidentId", incident.getId(),
                            "status", newStatus.name()));
        } catch (Exception e) {
            log.debug("WebSocket notification failed: {}", e.getMessage());
        }

        return toDto(incident);
    }

    @Transactional
    public IncidentCommentDto addComment(Long incidentId, String content, User currentUser) {
        Incident incident = incidentRepository.findById(incidentId)
                .orElseThrow(() -> new ResourceNotFoundException("Incident", "id", incidentId));

        IncidentComment comment = new IncidentComment(incident, currentUser, content);
        comment = commentRepository.save(comment);

        IncidentCommentDto dto = new IncidentCommentDto();
        dto.setId(comment.getId());
        dto.setIncidentId(incidentId);
        dto.setUserId(currentUser.getId());
        dto.setUserName(currentUser.getFullName());
        dto.setContent(comment.getContent());
        dto.setCreatedAt(comment.getCreatedAt().toString());
        return dto;
    }

    @Transactional(readOnly = true)
    public PagedResponse<IncidentCommentDto> getComments(Long incidentId, int page, int size) {
        Page<IncidentComment> comments = commentRepository.findByIncidentIdOrderByCreatedAtDesc(
                incidentId, PageRequest.of(page, size));
        List<IncidentCommentDto> dtos = comments.getContent().stream().map(c -> {
            IncidentCommentDto dto = new IncidentCommentDto();
            dto.setId(c.getId());
            dto.setIncidentId(incidentId);
            dto.setUserId(c.getUser().getId());
            dto.setUserName(c.getUser().getFullName());
            dto.setContent(c.getContent());
            dto.setCreatedAt(c.getCreatedAt().toString());
            return dto;
        }).toList();
        return new PagedResponse<>(dtos, comments.getNumber(), comments.getSize(),
                comments.getTotalElements(), comments.getTotalPages(), comments.isLast());
    }

    /**
     * Auto-resolve incidents when API recovers.
     */
    @Transactional
    public void resolveAutoIncidents(MonitoredApi api) {
        List<Incident> activeIncidents = incidentRepository.findActiveByApiId(api.getId());
        for (Incident incident : activeIncidents) {
            if (incident.getAutoGenerated()) {
                incident.setStatus(IncidentStatus.RESOLVED);
                incident.setResolvedAt(LocalDateTime.now());
                incidentRepository.save(incident);
                notificationService.notifyIncidentResolved(incident);
                log.info("Auto-resolved incident {} for recovered API: {}", incident.getId(), api.getName());
            }
        }
    }

    private IncidentDto toDto(Incident incident) {
        IncidentDto dto = new IncidentDto();
        dto.setId(incident.getId());
        dto.setTitle(incident.getTitle());
        dto.setDescription(incident.getDescription());
        dto.setApiId(incident.getApi().getId());
        dto.setApiName(incident.getApi().getName());
        dto.setSeverity(incident.getSeverity());
        dto.setStatus(incident.getStatus());
        dto.setAutoGenerated(incident.getAutoGenerated());
        if (incident.getAssignedTo() != null) {
            dto.setAssignedToId(incident.getAssignedTo().getId());
            dto.setAssignedToName(incident.getAssignedTo().getFullName());
        }
        if (incident.getCreatedBy() != null) {
            dto.setCreatedById(incident.getCreatedBy().getId());
            dto.setCreatedByName(incident.getCreatedBy().getFullName());
        }
        if (incident.getResolvedBy() != null) {
            dto.setResolvedByName(incident.getResolvedBy().getFullName());
        }
        dto.setResolvedAt(incident.getResolvedAt() != null ? incident.getResolvedAt().toString() : null);
        dto.setCreatedAt(incident.getCreatedAt() != null ? incident.getCreatedAt().toString() : null);
        dto.setUpdatedAt(incident.getUpdatedAt() != null ? incident.getUpdatedAt().toString() : null);
        return dto;
    }

    private PagedResponse<IncidentDto> toPagedResponse(Page<Incident> page) {
        return new PagedResponse<>(page.getContent().stream().map(this::toDto).toList(),
                page.getNumber(), page.getSize(), page.getTotalElements(), page.getTotalPages(), page.isLast());
    }
}

